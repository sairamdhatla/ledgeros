"""Render machine-readable and human-readable evaluation reports."""

from __future__ import annotations

import json
from pathlib import Path

from .metrics import EvaluationMetrics, metrics_to_dict


def write_json(metrics: EvaluationMetrics, path: Path) -> None:
    path.write_text(json.dumps(metrics_to_dict(metrics), indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _percent(value: float) -> str:
    return f"{value:.2%}"


def render_markdown(metrics: EvaluationMetrics) -> str:
    lines = [
        "# LedgerOS Reconciliation Evaluation",
        "",
        "This report was generated by running the deterministic reconciliation engine against the generated operational CSV files and comparing results with `ground_truth.csv`.",
        "",
        "## Summary",
        "",
        f"- Total cases: {metrics.total_cases}",
        f"- Exact status accuracy: {_percent(metrics.exact_status_accuracy)}",
        f"- False auto-resolution count: {metrics.false_auto_resolution_count}",
        f"- False auto-resolution rate: {_percent(metrics.false_auto_resolution_rate)} (denominator: engine `AUTO_RESOLVED` results)",
        f"- Cases returned as `UNRESOLVED`: {metrics.unresolved_case_count}",
        "",
        "## Status Precision",
        "",
        "| Predicted status | Precision |",
        "|---|---:|",
    ]
    lines.extend(f"| `{status}` | {_percent(value)} |" for status, value in metrics.status_precision.items())
    lines.extend(["", "## Scenario Accuracy", "", "| Scenario | Accuracy |", "|---|---:|"])
    lines.extend(f"| `{scenario}` | {_percent(value)} |" for scenario, value in metrics.scenario_accuracy.items())
    lines.extend(["", "## Confusion Matrix", "", "Rows are expected statuses; columns are engine statuses.", ""])
    statuses = list(metrics.confusion_matrix)
    lines.append("| Expected \\ Actual | " + " | ".join(f"`{status}`" for status in statuses) + " |")
    lines.append("|---|" + "---:|" * len(statuses))
    for expected, actuals in metrics.confusion_matrix.items():
        lines.append("| `" + expected + "` | " + " | ".join(str(actuals[status]) for status in statuses) + " |")
    lines.extend(["", "## Findings", "", "### What the engine got wrong", ""])
    if metrics.mismatches:
        lines.extend(
            f"- `{mismatch['transaction_id']}` ({mismatch['scenario']}): expected `{mismatch['expected_status']}`, got `{mismatch['actual_status']}`."
            for mismatch in metrics.mismatches
        )
    else:
        lines.append("- No status mismatches were found.")
    lines.extend([
        "",
        "### What it could not safely resolve",
        "",
        f"- The engine returned `{metrics.unresolved_case_count}` cases as `UNRESOLVED`; these require investigation because the available evidence did not support a safe deterministic explanation.",
        "",
        "### Weak scenarios",
        "",
    ])
    weak = [scenario for scenario, accuracy in metrics.scenario_accuracy.items() if accuracy < 1.0]
    lines.append("- " + (", ".join(f"`{scenario}`" for scenario in weak) if weak else "No scenario had less than 100% accuracy."))
    lines.extend(["", "## Integrity Checks", ""])
    lines.extend([
        f"- Ground-truth access detected in reconciliation package: `{metrics.integrity_checks.ground_truth_access_detected}`",
        f"- Hard-coded expected results detected: `{metrics.integrity_checks.hardcoded_expected_results_detected}`",
        f"- Missing transaction IDs: `{list(metrics.integrity_checks.missing_transaction_ids)}`",
        f"- Duplicate result IDs: `{list(metrics.integrity_checks.duplicate_result_ids)}`",
        f"- Results without transaction IDs: `{metrics.integrity_checks.results_without_transaction_ids}`",
        f"- Overall integrity check passed: `{metrics.integrity_checks.passed}`",
        "",
        "## Metric Definitions",
        "",
        "- Status precision is correct predictions divided by all engine predictions of that status.",
        "- False auto-resolution rate is false `AUTO_RESOLVED` predictions divided by all engine `AUTO_RESOLVED` predictions.",
        "- Scenario names `gateway_fee` and `settlement_timing` are report aliases for the corresponding ground-truth scenario labels.",
    ])
    return "\n".join(lines) + "\n"


def write_markdown(metrics: EvaluationMetrics, path: Path) -> None:
    path.write_text(render_markdown(metrics), encoding="utf-8")